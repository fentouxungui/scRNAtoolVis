# Declarative parameter specifications for the scRNAtoolVis Shiny app.
#
# Each specification maps one exported plotting function to a set of UI
# controls.  The generic module in mod_plot.R turns these specifications into
# widgets, builds the argument list, and calls the original function with
# do.call().  No plotting logic is duplicated here.

ctl <- function(id, label, type, arg = id, value = NULL, group = "Basic",
                required = FALSE, choices = NULL, min = NULL, max = NULL,
                step = NULL, help = NULL) {
  list(
    id = id,
    label = label,
    type = type,
    arg = arg,
    value = value,
    group = group,
    required = required,
    choices = choices,
    min = min,
    max = max,
    step = step,
    help = help
  )
}

